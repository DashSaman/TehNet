"""Validate this documentation handoff locally; no network or live tests.

Run from repository root: rtk proxy python -X utf8 qa/agent-handoff-2026-10-25/verify-docs.py
Historical verification receipts are read, never regenerated by this script.
"""
from pathlib import Path
from urllib.parse import unquote, urlsplit
import datetime
import hashlib
import json
import re
import subprocess

root = Path(__file__).resolve().parents[2]
out = Path(__file__).resolve().parent
guide = root / 'docs/agent-continuation.fa.md'
checks = []
def check(name, condition):
    if not condition:
        raise AssertionError(name)
    checks.append(name)
def read(path):
    return json.loads((root / path).read_text(encoding='utf-8'))
def sha(path):
    return hashlib.sha256(path.read_text(encoding='utf-8').encode('utf-8')).hexdigest()
def git(*args):
    result = subprocess.run(['rtk', 'proxy', 'git', *args], cwd=root,
        capture_output=True, text=True, encoding='utf-8')
    if result.returncode:
        raise RuntimeError(result.stdout + result.stderr)
    return result.stdout.strip()

text = guide.read_text(encoding='utf-8')
local_links = []
for raw in re.findall(r'\[[^\]]+\]\(([^)]+)\)', text):
    target = raw.strip('<>')
    if urlsplit(target).scheme:
        continue
    relative = unquote(target.split('#', 1)[0])
    resolved = (guide.parent / relative).resolve()
    check('reference exists: ' + relative, resolved.exists() and resolved.is_relative_to(root))
    local_links.append(relative)
check('guide has substantial source map', len(local_links) >= 40)
for name in ['README.md', 'AGENTS.md', 'HANDOFF.md']:
    check('entry point: ' + name, 'docs/agent-continuation.fa.md' in (root / name).read_text(encoding='utf-8'))
check('original versioned user request present', (root / 'docs/requirements-store-2026-10-15.fa.txt').stat().st_size > 4000)
for name in [
    'site/themes/tehnet', 'site/plugins/tehnet-core/includes/class-quotes.php',
    'site/plugins/tehnet-store/includes/class-policy.php',
    'site/plugins/tehnet-store/includes/class-account.php',
    'site/plugins/tehnet-store/includes/class-operations.php',
    'site/plugins/tehnet-store/includes/class-erp.php',
    'site/plugins/tehnet-store/includes/class-zarinpal-sandbox.php',
    'site/plugins/tehnet-store/includes/class-product-evidence.php',
    'site/plugins/tehnet-store/includes/class-product-visuals.php',
    'site/plugins/tehnet-store/assets/reviewed-model.js',
    'site/plugins/tehnet-store/assets/model-controls.js', 'integrations/tehnet_erp',
    'site/mu-plugins/tehnet-search-metadata.php', 'site/mu-plugins/tehnet-technical-resources.php']:
    check('code map exists: ' + name, (root / name).exists())

exact = read('qa/exact-media-2026-10-18/verification.json')
native = read('qa/exact-media-2026-10-18/native-inventory.json')
shop = read('qa/shop-ux-2026-10-16/verification.json')
release = read('qa/shop-ux-2026-10-16/release.json')
check('historical exact evidence incomplete', exact['status'] == 'evidence-verified-publication-incomplete')
check('historical source counts', exact['catalogue_products'] == 25 and exact['original_image_files_sha256_verified'] == 23 and exact['manufacturer_research_sources'] == 17)
check('no exact models in historical inventory', exact['new_models_published'] == exact['qualified_exact_models_obtained'] == 0 and len(native['products']) == 25 and all(not p['model_available'] and not p['parts_available'] and not p['spin_frame_count'] for p in native['products']))
check('historical timestamps remain dated', native['observed_utc'].startswith('2026-10-18') and exact['verified_utc'].startswith('2026-10-18'))
check('historical public browser limit retained', shop['status'] == 'verified-with-production-browser-limit' and shop['production_browser']['status'] == 'incomplete' and shop['production_browser']['completed_checks'] == 12)
check('historical release manifest retained', release['status'] == 'published' and len(release['files']) == 22 and len(release['changed_files']) == 9)
for token in ['۲۵ اکتبر ۲۰۲۶', '۱۸ اکتبر', 'صفر MPN', '۱۲ بررسی', 'tmpfs', '77214', '77211', '77218', 'خود آرشیوها در Git نیستند', 'بدون بررسی ظرفیت']:
    check('continuation caveat: ' + token, token in text)

changed = set(git('diff', '--name-only', 'e7600b3', '--').splitlines())
changed.update(git('ls-files', '--others', '--exclude-standard').splitlines())
check('documentation scope only', all(p.endswith('.md') or p == '.gitattributes' or p.startswith('qa/agent-handoff-2026-10-25/') for p in changed))
git('diff', '--check')
check('git diff whitespace clean', True)
source_paths = ['docs/agent-continuation.fa.md', 'README.md', 'AGENTS.md', 'HANDOFF.md',
    'PROGRESS.md', 'TASKS.md', 'WORK_LOG.md', 'qa/agent-handoff-2026-10-25/verify-docs.py']
result = {
    'status': 'passed-documentation-integrity-only',
    'verified_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
    'client_date': '2026-10-25', 'source_base_commit': 'e7600b3',
    'checked_local_markdown_links': len(local_links), 'checks': checks,
    'sha256_utf8_lf': {p: sha(root / p) for p in source_paths},
    'historical_native_observed_utc': native['observed_utc'],
    'historical_exact_evidence_status': exact['status'],
    'historical_public_browser_status': shop['production_browser']['status'],
    'live_state_rechecked': False, 'runtime_tests_rerun': False,
    'production_writes': False, 'network_used_by_verifier': False,
    'setup_note': 'Initial reference check found the not-yet-created output receipt; receipt scaffold was added and all checks rerun successfully.',
    'limitations': ['Local references and recorded facts only; no fresh production or external-source validation',
        'Private backups, server access and stopped local previews were not tested',
        'Existing ERP/payment/model/public-browser blockers remain open']}
(out / 'verification.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
print(f'DOC_HANDOFF=PASSED; {len(local_links)} local links; {len(checks)} checks; historical receipts preserved; no live/runtime tests')
