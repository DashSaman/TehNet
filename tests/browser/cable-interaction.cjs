/* Drive actual mouse/touch gestures and the local demo toolbar. */
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {chromium}=require('playwright');
const out=path.resolve(process.argv[2]),base='http://127.0.0.1:18084',checks=[],errors=[];
const check=(value,name)=>{assert(value,name);checks.push(name)};
const orbit=p=>p.locator('model-viewer').evaluate(v=>{const o=v.getCameraOrbit();return {theta:o.theta,phi:o.phi,radius:o.radius,framing:o.radius*Math.tan(v.getFieldOfView()*Math.PI/360)}});
const target=p=>p.locator('model-viewer').evaluate(v=>{const o=v.getCameraTarget();return {x:o.x,y:o.y,z:o.z}});
const action=(p,name)=>p.locator(`[data-demo-action="${name}"]`);
const load=async p=>{await p.locator('[data-demo-toolbar]').waitFor({state:'visible',timeout:30000});await p.locator('model-viewer').scrollIntoViewIfNeeded()};

(async()=>{
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  page.setDefaultTimeout(8000);
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base,{waitUntil:'networkidle'});
  check(await page.locator('#photo-panel').isVisible(),'ordinary URL retains real-photo default');
  await page.locator('[data-open-model]').click();await load(page);
  check(await page.locator('#model-panel').isVisible(),'prominent 360 button opens interactive GLB');
  check((await page.locator('#model-gesture-help').innerText()).includes('بچرخانید'),'gesture instructions visible');
  check(await action(page,'rotate').isDisabled(),'automatic motion disabled under reduced-motion preference');
  const initial=await orbit(page),initialTarget=await target(page);
  await action(page,'zoom-in').click();
  await page.waitForFunction(size=>{const v=document.querySelector('model-viewer');return v.getCameraOrbit().radius*Math.tan(v.getFieldOfView()*Math.PI/360)<size*.98},initial.framing);
  check(true,'zoom-in button increases actual model projection size');
  const close=await orbit(page);await action(page,'zoom-out').click();
  await page.waitForFunction(size=>{const v=document.querySelector('model-viewer');return v.getCameraOrbit().radius*Math.tan(v.getFieldOfView()*Math.PI/360)>size*1.02},close.framing);
  check(true,'zoom-out button decreases actual model projection size');

  await page.locator('model-viewer').scrollIntoViewIfNeeded();
  let box=await page.locator('model-viewer').boundingBox(),before=await orbit(page);
  await page.mouse.move(box.x+box.width*.45,box.y+box.height*.45);await page.mouse.down();
  await page.mouse.move(box.x+box.width*.59,box.y+box.height*.34,{steps:14});await page.mouse.up();
  await page.waitForFunction(o=>Math.abs(document.querySelector('model-viewer').getCameraOrbit().theta-o.theta)>.05,before);
  check(true,'left-button drag rotates actual 3D camera');
  const panBefore=await target(page);
  await page.mouse.move(box.x+box.width*.45,box.y+box.height*.45);await page.mouse.down({button:'right'});
  await page.mouse.move(box.x+box.width*.50,box.y+box.height*.50,{steps:10});await page.mouse.up({button:'right'});
  await page.waitForFunction(t=>{const n=document.querySelector('model-viewer').getCameraTarget();return Math.hypot(n.x-t.x,n.y-t.y,n.z-t.z)>.01},panBefore);
  check(true,'right-button drag pans actual camera target');
  await action(page,'home').click();
  await page.waitForFunction(t=>{const n=document.querySelector('model-viewer').getCameraTarget();return Math.hypot(n.x-t.x,n.y-t.y,n.z-t.z)<.01},initialTarget);
  check(Math.abs((await orbit(page)).theta-initial.theta)<.01,'home restores angle and pan target');
  check(Math.abs((await orbit(page)).radius-initial.radius)<.05,'home restores fitted zoom');
  await action(page,'fullscreen').click();
  await page.waitForFunction(()=>document.fullscreenElement?.matches('[data-model-canvas]')&&document.querySelector('[data-demo-action="fullscreen"]').getAttribute('aria-pressed')==='true');
  check(await action(page,'fullscreen').getAttribute('aria-pressed')==='true','fullscreen keeps visible toolbar and accurate state');
  check(await page.locator('model-viewer').evaluate(v=>v.clientHeight>innerHeight*.7),'fullscreen enlarges actual model canvas');
  await page.screenshot({path:path.join(out,'fullscreen-desktop.png'),fullPage:false});
  await action(page,'fullscreen').click();await page.waitForFunction(()=>!document.fullscreenElement);
  check(true,'fullscreen exits through its own control');
  await page.screenshot({path:path.join(out,'interactive-desktop.png'),fullPage:true});

  const mobileContext=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true,reducedMotion:'reduce'});
  const mobile=await mobileContext.newPage();mobile.on('pageerror',e=>errors.push(e.message));
  mobile.setDefaultTimeout(8000);
  await mobile.goto(base+'/?view=3d',{waitUntil:'networkidle'});await load(mobile);
  const mobileInitial=await orbit(mobile);
  check(await mobile.locator('#model-panel').isVisible(),'direct 3D URL opens interactive panel');
  check(await mobile.locator('model-viewer').getAttribute('touch-action')==='none','explicit interactive canvas receives touch gestures');
  const cdp=await mobileContext.newCDPSession(mobile);
  const touch=async(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([id,x,y])=>({id,x,y}))});
  box=await mobile.locator('model-viewer').boundingBox();
  const x=box.x+box.width*.48,y=box.y+box.height*.45;
  before=await orbit(mobile);await touch('touchStart',[[1,x,y]]);
  for(let i=1;i<=8;i++)await touch('touchMove',[[1,x+i*9,y-i*3]]);
  await touch('touchEnd',[]);
  await mobile.waitForFunction(o=>Math.abs(document.querySelector('model-viewer').getCameraOrbit().theta-o.theta)>.05,before);
  check(true,'one-finger touch drag rotates actual model');
  before=await orbit(mobile);await touch('touchStart',[[1,x-15,y],[2,x+15,y]]);
  for(let i=1;i<=8;i++)await touch('touchMove',[[1,x-15-i*5,y],[2,x+15+i*5,y]]);
  await touch('touchEnd',[]);
  await mobile.waitForFunction(o=>{const v=document.querySelector('model-viewer');return v.getCameraOrbit().radius*Math.tan(v.getFieldOfView()*Math.PI/360)<o.framing*.95},before);
  check(true,'two-finger pinch zoom changes actual model projection size');
  const mobilePanBefore=await target(mobile);
  await touch('touchStart',[[1,x-15,y],[2,x+15,y]]);
  for(let i=1;i<=8;i++)await touch('touchMove',[[1,x-15+i*4,y+i*2],[2,x+15+i*4,y+i*2]]);
  await touch('touchEnd',[]);
  await mobile.waitForFunction(t=>{const n=document.querySelector('model-viewer').getCameraTarget();return Math.hypot(n.x-t.x,n.y-t.y,n.z-t.z)>.01},mobilePanBefore);
  check(true,'two-finger translation pans actual model target');
  await action(mobile,'home').click();
  await mobile.waitForFunction(o=>Math.abs(document.querySelector('model-viewer').getCameraOrbit().radius-o.radius)<.05,mobileInitial);
  check(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'mobile toolbar has no horizontal overflow');
  await mobile.locator('model-viewer').scrollIntoViewIfNeeded();
  await mobile.screenshot({path:path.join(out,'interactive-mobile.png'),fullPage:false});
  await mobileContext.close();

  const normal=await browser.newPage({viewport:{width:1280,height:900},reducedMotion:'no-preference'});
  normal.on('pageerror',e=>errors.push(e.message));
  await normal.goto(base+'/?view=3d',{waitUntil:'networkidle'});await load(normal);
  check(await action(normal,'rotate').getAttribute('aria-pressed')==='false','automatic rotation starts only after opt-in');
  const yaw=await normal.locator('model-viewer').evaluate(v=>v.turntableRotation);
  await action(normal,'rotate').click();await normal.waitForFunction(y=>document.querySelector('model-viewer').turntableRotation>y+.05,yaw);
  check(true,'automatic rotation changes native model turntable yaw');
  await action(normal,'rotate').click();
  check(await normal.locator('model-viewer').evaluate(v=>!v.autoRotate),'stop button disables native automatic rotation');
  await action(normal,'rotate').click();await normal.locator('[data-view="photo"]').click();
  check(await normal.locator('model-viewer').evaluate(v=>!v.autoRotate),'switching to photo stops hidden motion');
  await normal.locator('[data-view="model"]').click();await action(normal,'rotate').click();
  await normal.emulateMedia({reducedMotion:'reduce'});
  await normal.waitForFunction(()=>!document.querySelector('model-viewer').autoRotate&&document.querySelector('[data-demo-action="rotate"]').disabled);
  check(true,'live reduced-motion preference stops automatic rotation');
  await action(normal,'home').click();
  check(await normal.locator('model-viewer').evaluate(v=>v.turntableRotation===0),'home clears automatic turntable rotation');
  check(errors.length===0,'no JavaScript errors across desktop and touch contexts');
  fs.writeFileSync(path.join(out,'interaction.json'),JSON.stringify({status:'passed',scope:'Local educational GLB; actual headless mouse/touch input, not physical mobile hardware',checks,js_errors:errors},null,2));
  console.log('CABLE_INTERACTION_CHECKS='+checks.length+' PASS');
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack);console.error('Last successful checks:',checks.slice(-3));process.exit(1)});
